package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type localeFile struct {
	Language string            `json:"language"`
	Aliases  []string          `json:"aliases"`
	Messages map[string]string `json:"messages"`
}

func main() {
	in := flag.String("in", "internal/pkg/i18n/locales", "directory containing locale JSON files")
	out := flag.String("out", "internal/pkg/i18n/catalog_gen.go", "generated Go output path")
	flag.Parse()
	locales, err := loadLocales(*in)
	if err != nil {
		fatal(err)
	}
	src, err := render(locales)
	if err != nil {
		fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fatal(err)
	}
}

func loadLocales(dir string) ([]localeFile, error) {
	var locales []localeFile
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(d.Name(), ".json") {
			return err
		}
		body, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		var loc localeFile
		if err := json.Unmarshal(body, &loc); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if strings.TrimSpace(loc.Language) == "" {
			return fmt.Errorf("%s: language is required", path)
		}
		if len(loc.Messages) == 0 {
			return fmt.Errorf("%s: messages must not be empty", path)
		}
		locales = append(locales, loc)
		return nil
	})
	sort.Slice(locales, func(i, j int) bool { return locales[i].Language < locales[j].Language })
	return locales, err
}

func render(locales []localeFile) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by make i18n; DO NOT EDIT.")
	fmt.Fprintln(&b, "package i18n")
	fmt.Fprintln(&b, "func init() {")
	for _, loc := range locales {
		sort.Strings(loc.Aliases)
		fmt.Fprintf(&b, "\tRegisterLanguage(%s", strconv.Quote(loc.Language))
		for _, alias := range loc.Aliases {
			fmt.Fprintf(&b, ", %s", strconv.Quote(alias))
		}
		fmt.Fprintln(&b, ")")
		keys := make([]string, 0, len(loc.Messages))
		for key, message := range loc.Messages {
			if strings.TrimSpace(key) == "" || strings.TrimSpace(message) == "" {
				return nil, fmt.Errorf("%s: message keys and values must not be empty", loc.Language)
			}
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for _, key := range keys {
			fmt.Fprintf(&b, "\tRegister(%s, %s, %s)\n", strconv.Quote(loc.Language), strconv.Quote(key), strconv.Quote(loc.Messages[key]))
		}
	}
	fmt.Fprintln(&b, "}")
	return format.Source(b.Bytes())
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "i18n-gen:", err)
	os.Exit(1)
}
